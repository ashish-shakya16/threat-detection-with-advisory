"""Embed the bibliography in main.tex as an IEEE-style thebibliography block.

Reads references.bib, orders entries by first \\cite in main.tex, formats them in IEEE
style and replaces everything between the BIBLIOGRAPHY markers in main.tex. This keeps
main.tex compilable without running BibTeX (single-file upload to Overleaf works).
Run: python paper/scripts/build_bibliography.py
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEX, BIB = ROOT / "main.tex", ROOT / "references.bib"
BEGIN, END = "% BEGIN BIBLIOGRAPHY (generated by scripts/build_bibliography.py)", "% END BIBLIOGRAPHY"


def parse_bib(text):
    entries = {}
    for match in re.finditer(r"@(\w+)\{([^,]+),", text):
        kind, key, pos = match.group(1).lower(), match.group(2).strip(), match.end()
        depth, i = 1, pos
        while depth:
            depth += {"{": 1, "}": -1}.get(text[i], 0)
            i += 1
        body, fields = text[pos:i - 1], {}
        j = 0
        while True:
            m = re.compile(r"\s*,?\s*(\w+)\s*=\s*\{").match(body, j)
            if not m:
                break
            start, depth, k = m.end(), 1, m.end()
            while depth:
                depth += {"{": 1, "}": -1}.get(body[k], 0)
                k += 1
            fields[m.group(1).lower()] = re.sub(r"\s+", " ", body[start:k - 1]).strip()
            j = k
        entries[key] = (kind, fields)
    return entries


def initials(first):
    out = []
    for token in first.split():
        parts = []
        for piece in token.split("-"):
            letters = re.sub(r"\\[`'^\"~=.uvHcdbtk]|[{}\\]", "", piece)
            if letters:
                parts.append(letters[0] + ".")
        if parts:
            out.append("-".join(parts))
    return " ".join(out)


def format_name(name):
    name = name.strip()
    if name.startswith("{") and name.endswith("}"):
        return name[1:-1]
    if "," in name:
        last, first = (p.strip() for p in name.split(",", 1))
        return f"{initials(first)}~{last}" if first else last
    return name


def format_authors(raw):
    names = [n for n in re.split(r"\s+and\s+", raw)]
    et_al = any(n.strip() == "others" for n in names)
    names = [format_name(n) for n in names if n.strip() != "others"]
    if et_al or len(names) > 6:
        return f"{names[0]} \\emph{{et al.}}"
    if len(names) == 1:
        return names[0]
    if len(names) == 2:
        return f"{names[0]} and {names[1]}"
    return ", ".join(names[:-1]) + ", and " + names[-1]


def pages(value):
    if re.fullmatch(r"\d+", value):
        return f"Art. no. {value}"
    art = re.fullmatch(r"(\d+):\d+--\d+:\d+", value)
    if art:
        return f"Art. no. {art.group(1)}"
    return f"pp. {value}"


def format_entry(kind, f):
    parts = [format_authors(f["author"]), f"``{f['title']},''"]
    if kind == "article":
        parts.append(f"\\emph{{{f['journal']}}}")
        if "volume" in f:
            parts.append(f"vol. {f['volume']}")
        if "number" in f:
            parts.append(f"no. {f['number']}")
        if "pages" in f:
            parts.append(pages(f["pages"]))
        parts.append(f["year"])
    elif kind == "inproceedings":
        parts.append(f"in \\emph{{{f['booktitle']}}}")
        parts.append(f["year"])
        if "pages" in f:
            parts.append(pages(f["pages"]))
    else:
        parts.append(f.get("howpublished", ""))
        parts.append(f["year"])
    if "doi" in f:
        parts.append(f"doi: {f['doi']}")
    if "note" in f:
        parts.append(f["note"])
    text = ", ".join(p for p in parts if p)
    return text.replace(",'', ", ",'' ") + "."


def main():
    tex, entries = TEX.read_text(encoding="utf-8"), parse_bib(BIB.read_text(encoding="utf-8"))
    order = []
    for group in re.findall(r"\\cite\{([^}]*)\}", tex.split(BEGIN)[0]):
        for key in (k.strip() for k in group.split(",")):
            if key not in order:
                order.append(key)
    missing = [k for k in order if k not in entries]
    if missing:
        raise SystemExit(f"cited keys missing from references.bib: {missing}")
    lines = [BEGIN, "\\begin{thebibliography}{99}"]
    for key in order:
        lines.append(f"\\bibitem{{{key}}} {format_entry(*entries[key])}")
    lines += ["\\end{thebibliography}", END]
    block = "\n\n".join(lines[:2]) + "\n\n" + "\n\n".join(lines[2:-2]) + "\n\n" + "\n".join(lines[-2:])
    if BEGIN in tex:
        tex = tex[:tex.index(BEGIN)] + block + tex[tex.index(END) + len(END):]
    else:
        tex = tex.replace("\\bibliographystyle{IEEEtran}\n\\bibliography{references}", block)
    TEX.write_text(tex, encoding="utf-8")
    print(f"embedded {len(order)} references; unused bib entries: {sorted(set(entries) - set(order)) or 'none'}")


if __name__ == "__main__":
    main()
